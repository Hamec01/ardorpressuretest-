# === КАЛЬКУЛЯТОР ПЛОЩАДИ СТЕН (Приложение для ремонта) ===

# Шаг 1: Размеры первой стены (в метрах)
wall1_height = 2.50  # Высота: 2.5 метра
wall1_width = 4.50   # Длина: 4.5 метра

# Считаем площадь первой стены (Высота * Длина)
wall1_area = wall1_height * wall1_width

# Шаг 2: Размеры второй стены (в метрах)
wall2_height = 2.50  # Высота: 2.5 метра
wall2_width = 3.00   # Длина: 3.0 метра

# Считаем площадь второй стены
wall2_area = wall2_height * wall2_width

# Шаг 3: Складываем площади всех стен (Общая квадратные метры)
total_area = wall1_area + wall2_area

# Шаг 4: Выводим результат на экран
print("--- РЕЗУЛЬТАТ РАСЧЕТА СТРОИТЕЛЬНЫХ МАТЕРИАЛОВ ---")
print("Площадь 1-й стены: " + str(wall1_area) + " кв.м")
print("Площадь 2-й стены: " + str(wall2_area) + " кв.м")
print("ОБЩАЯ ПЛОЩАДЬ СТЕН: " + str(total_area) + " кв.м")
